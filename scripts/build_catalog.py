#!/usr/bin/env python3
"""Build the published catalog from the app and collection files (ASCAT-009
to ASCAT-014).

Usage:
    python3 scripts/build_catalog.py           # write the generated files
    python3 scripts/build_catalog.py --check   # write nothing; exit 1 naming each stale file

Reads only apps/, collections/, status/, sources/repology.json (package
names per manager by app name, used where an app file names none) and
sources/releases.json (GitHub repositories whose latest release has
binaries). Writes assets/catalog.json and assets/suite-apps.txt. The same
files give the same bytes. Stdlib only (Python 3.11+).
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import appfiles as af  # noqa: E402

ROOT = af.ROOT

# The catalog schema the released clients parse (ASCAT-012).
SCHEMA = 1
# The suite installer size of each collection (ASCAT-014): desktop is part
# of essentials. The catalog tier of each size.
SIZE = {"desktop": "essentials", "essentials": "essentials", "recommended": "recommended", "extras": "extras"}
TIER = {"essentials": "default", "recommended": "recommended", "extras": "optional"}
ORDER = ["id", "name", "bin", "variants", "category", "description", "homepage", "releases", "cli", "needs_url",
         "recipe", "agent", "pkg", "tier", "set", "collection", "sources", "status"]
RECIPE = ["install", "method", "verified", "os", "requires_cwd", "tip"]
PACKAGES = ("essentials", "recommended", "extras")
RECOMMENDS = re.compile(r"^recommends = \[[^\n]*\]\n|^recommends = \[\n.*?^\]\n", re.S | re.M)
HEADER = ("# Generated by scripts/build_catalog.py from apps/ and collections/. Do not edit.\n"
          "# size:group:check:apt:dnf:pacman:brew, size:script:name, or size:release:check:repo:amd64:arm64\n")


class BuildError(Exception):
    pass


def _json(path, key, default):
    return json.loads(path.read_text(encoding="utf-8"))[key] if path.exists() else default


def membership(apps, collections):
    """{id: collection name}; BuildError on an unknown id or an app in two collections (ASCAT-022)."""
    where, problems = {}, []
    for c in collections:
        for i in c["apps"]:
            if i not in apps:
                problems.append(f"collections/{c['name']}.toml: {i!r} has no apps/{i}.toml")
            elif i in where:
                problems.append(f"{i}: in collections {where[i]!r} and {c['name']!r}")
            else:
                where[i] = c["name"]
    if problems:
        raise BuildError("\n".join(problems))
    return where


def package_names(app, repology):
    """{manager: name} for all four managers ("" = none): the app file's
    [install.pkg] wins name by name over sources/repology.json."""
    found = repology.get(app.get("name", ""), {})
    given = app.get("install", {}).get("pkg", {})
    return {m: given.get(m, found.get(m, "")) for m in af.MANAGERS}


def app_status(status):
    """The catalog's view of status/<id>.json (ASCAT-016, ASCAT-017):
    {platform: result}, and the upstream health flags under "health"."""
    out = {p: s["result"] for p, s in sorted(status.get("platforms", {}).items())}
    flags = sorted(k for k, v in status.get("health", {}).items() if k != "since" and v)
    if flags:
        out["health"] = flags
    return out


def catalog_entry(app, coll, repology, released, status=None):
    """The catalog.json entry of a Store app, in the released clients' format."""
    e = {k: app[k] for k in ("id", "name", "bin", "variants", "category", "description", "homepage", "agent")
         if k in app}
    for k in ("cli", "needs_url"):
        if app.get(k):
            e[k] = True
    if af.gh_repo(app.get("homepage")) in released:
        e["releases"] = True
    r = app.get("install", {}).get("recipe")
    if r:
        r = dict(r)
        if "requires_cwd" in app:
            r["requires_cwd"] = app["requires_cwd"]
        if "tip" in app.get("notes", {}):
            r["tip"] = app["notes"]["tip"]
        e["recipe"] = {k: r[k] for k in RECIPE if k in r}
    pkg = {m: n for m, n in package_names(app, repology).items() if n}
    if pkg:
        e["pkg"] = pkg
    size = SIZE.get(coll)
    e["tier"] = TIER[size] if size else "optional"
    if size:
        e["set"] = size
        e["collection"] = coll
    e["sources"] = list(app.get("source", {}).get("lists", []))
    if status:
        e["status"] = app_status(status)
    return {k: e[k] for k in ORDER if k in e}


def suite_lines(apps, collections, repology):
    """The suite installer's list (ASCAT-014): a package line per member,
    then a script line per member with its own method, then a release line
    per member with a release to fall back on."""
    pkgs, scripts, releases = [], [], []
    for c in collections:
        size = SIZE[c["name"]]
        for i in c["apps"]:
            a = apps[i]
            inst = a.get("install", {})
            check = a.get("check", a.get("bin", ""))
            if inst.get("script"):
                scripts.append([size, "script", inst["script"]])
            elif check:
                names = package_names(a, repology)
                pkgs.append([size, a.get("group", "apps"), check] + [names[m] for m in af.MANAGERS])
            elif not (inst.get("deb") or inst.get("pkg", {}).get("apt")):
                raise BuildError(f"apps/{i}.toml: in a collection with no check, script or deb, so nothing installs it")
            rel = inst.get("release")
            if rel:
                if not check:
                    raise BuildError(f"apps/{i}.toml: a release needs a check command")
                releases.append([size, "release", check, rel["repo"], rel.get("amd64", ""), rel.get("arm64", "")])
    lines = pkgs + scripts + releases
    for f in lines:
        if any(":" in x for x in f):
            raise BuildError(f"{f[2]}: ':' is the suite list's field separator")
    return HEADER + "".join(":".join(f) + "\n" for f in lines)


def recommends(apps, collection, repology):
    """The Debian Recommends of a collection's metapackage (ASPUB-003), in
    collection order: each member's `[install] deb`, else its apt name.
    Service members (Suggests, offered separately) and members with their
    own suite method are left out."""
    out = []
    for i in collection["apps"]:
        a, inst = apps[i], apps[i].get("install", {})
        if a.get("group") == "services" or inst.get("script"):
            continue
        deb = inst.get("deb") or package_names(a, repology)["apt"]
        if deb:
            out.append(deb)
    return out


def with_recommends(text, recs, name):
    """The packaging TOML text with its recommends array replaced."""
    if not RECOMMENDS.search(text):
        raise BuildError(f"packaging/{name}.toml: no recommends array")
    body = "".join(f"  {json.dumps(r)},\n" for r in recs)
    new = f"recommends = [\n{body}]\n" if recs else "recommends = []\n"
    return RECOMMENDS.sub(lambda _: new, text, count=1)


def build(root=ROOT):
    """{relative path: text} of every generated file."""
    apps = af.load_apps(root / "apps")
    collections = af.load_collections(root / "collections")
    repology = _json(root / "sources" / "repology.json", "names", {})
    released = set(_json(root / "sources" / "releases.json", "repos", []))
    where = membership(apps, collections)
    entries, problems = [], []
    for i, a in apps.items():
        if a.get("store", True):
            st = root / "status" / f"{i}.json"
            status = json.loads(st.read_text(encoding="utf-8")) if st.exists() else None
            entries.append(catalog_entry(a, where.get(i), repology, released, status))
    for e in entries:
        problems += [f"apps/{e['id']}.toml: {e['name']}: missing {k}" for k in
                     ("bin", "category", "description", "homepage") if not e.get(k)]
    if problems:
        raise BuildError("\n".join(problems))
    entries.sort(key=lambda e: (e["category"].lower(), e["name"].lower(), e["id"]))
    suite = suite_lines(apps, collections, repology)
    doc = {
        "schema": SCHEMA,
        "apps": entries,
        "collections": [dict({k: c[k] for k in ("name", "description", "includes", "apps") if k in c},
                             recommends=recommends(apps, c, repology)) for c in collections],
        "suite_apps": suite,
    }
    out = {
        "assets/catalog.json": json.dumps(doc, ensure_ascii=False, indent=1) + "\n",
        "assets/suite-apps.txt": suite,
    }
    # The metapackages built here; tetron-wm-desktop stays in tetron-wm, which
    # reads its recommends from the catalog's desktop collection (ASPUB-004).
    for c in collections:
        p = root / "packaging" / f"{c['name']}.toml"
        if c["name"] in PACKAGES and p.exists():
            out[f"packaging/{c['name']}.toml"] = with_recommends(p.read_text(encoding="utf-8"),
                                                                 recommends(apps, c, repology), c["name"])
    return out


def stale(root=ROOT):
    """The generated files that differ from what the inputs give."""
    out = build(root)
    return [p for p, text in out.items()
            if not (root / p).exists() or (root / p).read_text(encoding="utf-8") != text], out


def write(root=ROOT):
    _, out = stale(root)
    for p, text in out.items():
        (root / p).write_text(text, encoding="utf-8")
    return out


def main(argv):
    try:
        if "--check" in argv:
            bad, _ = stale()
            for p in bad:
                print(f"build_catalog: {p} is stale; run python3 scripts/build_catalog.py", file=sys.stderr)
            return 1 if bad else 0
        for p in write():
            print(f"wrote {p}")
        return 0
    except (BuildError, af.FileError) as e:
        print(f"build_catalog: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
